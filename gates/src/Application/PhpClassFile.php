<?php

declare(strict_types=1);

namespace Gates\Application;

use Gates\Domain\RegexCaptures;
use InvalidArgumentException;
use Override;

use function array_filter;
use function array_map;
use function array_unique;
use function array_values;
use function count;
use function explode;
use function implode;
use function in_array;
use function sort;
use function sprintf;
use function str_replace;
use function strrpos;
use function substr;

use const SORT_FLAG_CASE;
use const SORT_STRING;

/**
 * Lays out one generated class file the way Pint and PHPCS leave it (#92): the
 * strict-types header, the namespace, the imports sorted and the class
 * docblock. The build's generated wiring is
 * committed and gated like hand-written code, so its layout must already be
 * the formatter's.
 */
final readonly class PhpClassFile
{
    use RegexCaptures;

    /**
     * The most classes one class may depend on (PHPMD's coupling between objects).
     */
    private const int MAX_COUPLING = 15;

    /**
     * @param string       $namespace The file's namespace.
     * @param list<string> $classes   The classes it uses; those in its own namespace are not imported.
     * @param list<string> $functions The global functions it imports.
     * @param string       $docblock  The class docblock's text, one line per array entry joined by newlines.
     * @param string       $class     The class declaration and body, from `final readonly class` to its closing brace.
     *
     * @throws InvalidArgumentException When it would depend on more than 15 classes, or import two with one short name.
     *
     * @return string The file.
     */
    public function file(string $namespace, array $classes, array $functions, string $docblock, string $class): string
    {
        $this->checkFits(array_values(array_unique($classes)), $class);
        $functionImports = array_map(static fn (string $function): string => 'use function ' . $function . ';', $functions);
        $groups = array_filter([$this->imports($namespace, $classes), $functionImports], static fn (array $group): bool => $group !== []);
        $lines = ['<?php', '', 'declare(strict_types=1);', '', 'namespace ' . $namespace . ';', ''];

        foreach ($groups as $group) {
            $lines = [...$lines, ...$group, ''];
        }

        return implode("\n", [...$lines, '/**', $docblock, ' */', $class]) . "\n";
    }

    /**
     * The class docblock of a generated file.
     *
     * @param string $from What it is generated from (`the module manifests`).
     * @param string $what What the class holds.
     *
     * @return string The docblock's lines.
     */
    public function generated(string $from, string $what): string
    {
        return ' * Generated by composer run build from ' . $from . ' (#92): ' . $what . "\n"
            . ' * Do not edit; change the manifest and run composer run build.';
    }

    /**
     * @param string $class A fully qualified class name.
     *
     * @return string Its short name.
     */
    public function short(string $class): string
    {
        $position = strrpos($class, '\\');

        return $position === false
            ? $class
            : substr($class, $position + 1);
    }

    /**
     * A generated class must pass the gates like hand-written code: PHPMD's
     * coupling of 15, and imports PHPCS can read, which no alias may rename.
     *
     * @param list<string> $classes The distinct classes it uses.
     * @param string       $class   Its declaration and body, for its name.
     *
     * @throws InvalidArgumentException When it would depend on more than 15 classes, or import two with one short name.
     */
    private function checkFits(array $classes, string $class): void
    {
        $name = self::regexMatch('/class (\\w+)/', $class)[1] ?? 'a generated class';

        $counted = $this->counted($classes, $class);

        if ($counted > self::MAX_COUPLING) {
            throw new InvalidArgumentException(sprintf(
                "the generated %s would depend on %d classes, over PHPMD's %d; split the module.",
                $name,
                $counted,
                self::MAX_COUPLING,
            ));
        }

        $shorts = array_map($this->short(...), $classes);

        if (count(array_unique($shorts)) !== count($shorts)) {
            throw new InvalidArgumentException(
                'the generated ' . $name . ' would import two classes with one short name; rename one: ' . implode(', ', $classes) . '.',
            );
        }
    }

    /**
     * @param list<string> $classes The distinct classes it uses.
     * @param string       $class   Its declaration and body.
     *
     * @return int How many of them PHPMD's coupling counts (#203): pdepend counts neither an attribute (`Override`)
     *             nor an interface the class implements, so neither is counted here.
     */
    private function counted(array $classes, string $class): int
    {
        $implemented = explode(',', str_replace(' ', '', self::regexMatch('/implements ([\\w, ]+)/', $class)[1] ?? ''));
        $counted = 0;

        foreach ($classes as $used) {
            if ($used === Override::class || in_array($this->short($used), $implemented, true)) {
                continue;
            }

            $counted += 1;
        }

        return $counted;
    }

    /**
     * @param string       $namespace The file's namespace.
     * @param list<string> $classes   The classes it uses.
     *
     * @return list<string> The `use` lines, sorted, without the classes in its own namespace.
     */
    private function imports(string $namespace, array $classes): array
    {
        $classes = array_unique($classes);
        sort($classes, SORT_STRING | SORT_FLAG_CASE);
        $lines = [];

        foreach ($classes as $class) {
            if ($this->namespaceOf($class) === $namespace) {
                continue;
            }

            $lines[] = 'use ' . $class . ';';
        }

        return $lines;
    }

    /**
     * @param string $class A fully qualified class name.
     *
     * @return string Its namespace; empty for a global class.
     */
    private function namespaceOf(string $class): string
    {
        $position = strrpos($class, '\\');

        return $position === false
            ? ''
            : substr($class, 0, $position);
    }
}
