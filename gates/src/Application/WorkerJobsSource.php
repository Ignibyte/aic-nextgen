<?php

declare(strict_types=1);

namespace Gates\Application;

use AIC\Controller\Contracts\Job;
use AIC\Database\Contracts\Database;
use AIC\Queue\Domain\WorkerJobs;
use Gates\Domain\WorkerJob;
use InvalidArgumentException;
use Override;

use function array_map;
use function implode;
use function sprintf;
use function var_export;

/**
 * Writes an interpreted worker's `src/Generated/<Name>Jobs.php` (#336): its
 * jobs by name, each built from the database and the app's root.
 */
final readonly class WorkerJobsSource
{
    /** The class, around its entries. */
    private const string CLASS_SOURCE = <<<'PHP'
        final readonly class %sJobs implements WorkerJobs
        {
            /**
             * @param Database $database The app's database.
             * @param string   $root     The app's root, where `var/storage/` is.
             *
             * @return array<string, Job> The worker's jobs, by the name each is queued under.
             */
            #[Override]
            public function byName(Database $database, string $root): array
            {
                return [
        %s
                ];
            }
        }
        PHP;

    /**
     * @param PhpClassFile $phpClassFile Emits checked generated source.
     */
    public function __construct(
        private PhpClassFile $phpClassFile = new PhpClassFile(),
    ) {
    }

    /**
     * @param string          $worker    The worker's folder, `workers/<name>`.
     * @param string          $namespace Its namespace, `Worker\<Name>`.
     * @param string          $studly    Its name in StudlyCaps.
     * @param list<WorkerJob> $jobs      Its jobs, sorted by name.
     *
     * @throws InvalidArgumentException When the class would not fit the gates.
     *
     * @return string The generated class.
     */
    public function file(string $worker, string $namespace, string $studly, array $jobs): string
    {
        $classes = [Job::class, Database::class, WorkerJobs::class, Override::class];

        foreach ($jobs as $job) {
            $classes = [...$classes, $job->class, ...$job->uses];
        }

        $docblock = ' * Generated by composer run build from ' . $worker . "/src/Job/ (#336): the worker's jobs by name.\n"
            . ' * Do not edit; change the jobs and run composer run build.';

        return $this->phpClassFile->file(
            $namespace . '\\Generated',
            $classes,
            [],
            $docblock,
            sprintf(self::CLASS_SOURCE, $studly, $this->entries($jobs)),
        );
    }

    /**
     * @param list<WorkerJob> $jobs The jobs.
     *
     * @return string Each job's line in the returned list.
     */
    private function entries(array $jobs): string
    {
        return implode("\n", array_map(
            fn (WorkerJob $workerJob): string => sprintf(
                '            %s => new %s(%s),',
                var_export($workerJob->name, true),
                $this->phpClassFile->short($workerJob->class),
                implode(', ', $workerJob->arguments),
            ),
            $jobs,
        ));
    }
}
