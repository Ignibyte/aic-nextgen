<?php

declare(strict_types=1);

namespace Gates\Phpmd;

use function sprintf;

/**
 * Writes the PHPMD registration from the actual kind-aware rule's class name.
 */
final readonly class RuleRegistration
{
    /**
     * @return string The deterministic custom ruleset consumed by PHPMD.
     */
    public function source(): string
    {
        return sprintf(<<<'XML'
            <?xml version="1.0"?>
            <ruleset name="AIC custom" xmlns="http://pmd.sf.net/ruleset/1.0.0">
                <description>Generated by aic-build from the custom PHPMD registration.</description>
                <rule name="UnusedFormalParameter"
                      message="Avoid unused parameters such as '{0}'."
                      class="%s"
                      externalInfoUrl="https://phpmd.org/rules/unusedcode.html#unusedformalparameter">
                    <description>Avoid unused parameters, except the one a kind or Block interface dictates (#56, #58).</description>
                    <priority>3</priority>
                </rule>
            </ruleset>

            XML, KindAwareUnusedFormalParameter::class);
    }
}
