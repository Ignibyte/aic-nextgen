<?php

declare(strict_types=1);

namespace Gates\Sniffs;

use Gates\Sniffs\Functions\KindAwareUnusedParameterSniff;

use function str_replace;
use function substr;

/**
 * Writes the PHPCS registration from the actual custom sniff's class name.
 */
final readonly class SniffRegistration
{
    /**
     * @return string The deterministic custom ruleset consumed by PHPCS.
     */
    public function source(): string
    {
        $path = '../src/' . str_replace('\\', '/', substr(KindAwareUnusedParameterSniff::class, 6)) . '.php';

        return '<?xml version="1.0"?>' . "\n"
            . '<ruleset name="AIC custom">' . "\n"
            . '    <description>Generated by aic-build from the custom sniff registration.</description>' . "\n"
            . '    <rule ref="' . $path . '"/>' . "\n"
            . '</ruleset>' . "\n";
    }
}
