<?php

declare(strict_types=1);

namespace AIC\Workflow\Application\Import;

use AIC\Workflow\Domain\Import\CodeCall;
use AIC\Workflow\Domain\Import\CodeList;
use AIC\Workflow\Domain\Import\CodeNode;
use AIC\Workflow\Domain\Import\CodeValue;
use AIC\Workflow\Domain\Import\ColumnKey;
use AIC\Workflow\Domain\Import\ImportedCheck;
use AIC\Workflow\Domain\Import\ImportedColumn;
use AIC\Workflow\Domain\Import\ImportedTable;

use function in_array;
use function str_ends_with;
use function strlen;
use function substr;

/**
 * An imported table made ready to write (#318): each key the database makes is one Schema declares (an identity, a
 * uuid key), and a check that only lists a text column's values becomes that column's `choice()`.
 */
final readonly class TablePreparer
{
    /**
     * @param PhpLiteral $phpLiteral Reads the choices back.
     */
    public function __construct(
        private PhpLiteral $phpLiteral = new PhpLiteral(),
    ) {
    }

    /**
     * @param ImportedTable $importedTable The table.
     * @param DumpFacts     $dumpFacts     Takes the notes.
     *
     * @return array{ImportedTable, list<string>} The table, and what Schema cannot declare of its keys.
     */
    public function prepare(ImportedTable $importedTable, DumpFacts $dumpFacts): array
    {
        $findings = [];

        foreach ($importedTable->columns as $importedColumn) {
            $this->note($dumpFacts, $importedTable->name . '.' . $importedColumn->name, [$importedColumn->importedType->note]);
            $finding = $this->key($importedTable, $importedColumn, $dumpFacts);
            $findings = $finding === ''
                ? $findings
                : [...$findings, $finding];
        }

        return [$this->choices($importedTable, $dumpFacts), $findings];
    }

    /**
     * @param ImportedTable  $importedTable  The table.
     * @param ImportedColumn $importedColumn A column.
     * @param DumpFacts      $dumpFacts      Takes the notes.
     *
     * @return string Why its key has no Schema declaration; empty when it has one or is no key.
     */
    private function key(ImportedTable $importedTable, ImportedColumn $importedColumn, DumpFacts $dumpFacts): string
    {
        $name = $importedColumn->name;

        return match ($importedColumn->columnKey) {
            ColumnKey::None => '',
            ColumnKey::Identity, ColumnKey::IdentityByDefault, ColumnKey::Serial => $this->identity(
                $importedTable,
                $importedColumn,
                $dumpFacts,
            ),
            ColumnKey::UuidKey => $importedColumn->importedType->method === 'uuid' && $importedTable->primary === [$name]
                ? ''
                : $name . ' defaults to gen_random_uuid() but is not the uuid primary key, which only uuidKey() declares',
        };
    }

    /**
     * @param ImportedTable  $importedTable  The table.
     * @param ImportedColumn $importedColumn A column the database numbers.
     * @param DumpFacts      $dumpFacts      Takes the notes.
     *
     * @return string Why it cannot be an identity; empty when it becomes one.
     */
    private function identity(
        ImportedTable $importedTable,
        ImportedColumn $importedColumn,
        DumpFacts $dumpFacts,
    ): string {
        $method = $importedColumn->importedType->method;

        if ($importedColumn->nullable || !in_array($method, ['bigInteger', 'integer'], true)) {
            return $importedColumn->name . ' is numbered by the database but is not a non-null integer, which identity() needs';
        }

        $column = $importedTable->name . '.' . $importedColumn->name;
        $notes = [
            match ($importedColumn->columnKey) {
                ColumnKey::Serial => ' is a serial; it becomes an identity (GENERATED ALWAYS).',
                ColumnKey::IdentityByDefault => ' is GENERATED BY DEFAULT; identity() is GENERATED ALWAYS.',
                ColumnKey::None, ColumnKey::Identity, ColumnKey::UuidKey => '',
            },
            $method === 'integer' ? ' is an integer; identity() makes it a bigint.' : '',
        ];
        $this->note($dumpFacts, $column, $notes);

        return '';
    }

    /**
     * @param DumpFacts    $dumpFacts Takes the notes.
     * @param string       $column    The `<table>.<column>` they are about.
     * @param list<string> $notes     Each note's text after the column; an empty one is no note.
     */
    private function note(DumpFacts $dumpFacts, string $column, array $notes): void
    {
        foreach ($notes as $note) {
            if ($note === '') {
                continue;
            }

            $dumpFacts->note($column . $note);
        }
    }

    /**
     * @param ImportedTable $importedTable The table.
     * @param DumpFacts     $dumpFacts     Takes the notes.
     *
     * @return ImportedTable The table, each check that lists a text column's values made that column's choice.
     */
    private function choices(ImportedTable $importedTable, DumpFacts $dumpFacts): ImportedTable
    {
        $checks = [];

        foreach ($importedTable->checks as $importedCheck) {
            $chosen = $this->choice($importedTable, $importedCheck, $dumpFacts);

            if (!$chosen instanceof ImportedTable) {
                $checks[] = $importedCheck;
                continue;
            }

            $importedTable = $chosen;
        }

        return $importedTable->withChecks($checks);
    }

    /**
     * @param ImportedTable $importedTable The table.
     * @param ImportedCheck $importedCheck A check.
     * @param DumpFacts     $dumpFacts     Takes the note for a `character varying` column.
     *
     * @return ImportedTable|null The table with the column the check lists values for made a choice of them; null
     *                            when the check is not such a list.
     */
    private function choice(
        ImportedTable $importedTable,
        ImportedCheck $importedCheck,
        DumpFacts $dumpFacts,
    ): ?ImportedTable {
        $column = $this->choiceColumn($importedTable, $importedCheck);
        $values = $column instanceof ImportedColumn
            ? $this->values($importedCheck->predicate, $column->name)
            : [];

        if (!$column instanceof ImportedColumn || $values === []) {
            return null;
        }

        $spelled = $column->importedType->spelled;
        $this->note($dumpFacts, $importedTable->name . '.' . $column->name, [
            $column->importedType->method === 'string' ? ' is ' . $spelled . ' with a list of values; it becomes a text choice().' : '',
        ]);

        return $importedTable->withColumn($column->withChoices($values));
    }

    /**
     * @param ImportedTable $importedTable The table.
     * @param ImportedCheck $importedCheck A check.
     *
     * @return ImportedColumn|null The text column the check is named for (`<column>_check`), with no default term
     *                             but a literal and no generated one; null when there is none.
     */
    private function choiceColumn(ImportedTable $importedTable, ImportedCheck $importedCheck): ?ImportedColumn
    {
        if (!str_ends_with($importedCheck->name, '_check')) {
            return null;
        }

        $column = $importedTable->column(substr($importedCheck->name, 0, -strlen('_check')));

        return $column instanceof ImportedColumn && $column->importedType->isText() && $column->generated === null
            ? $column
            : null;
    }

    /**
     * @param CodeCall $codeCall A check's predicate.
     * @param string   $column   The column it should list values for.
     *
     * @return list<string> The values, when the predicate is exactly `oneOf(column, [text, …])`; otherwise none.
     */
    private function values(CodeCall $codeCall, string $column): array
    {
        $list = $codeCall->listArgument(1);

        return $codeCall->method === 'oneOf' && $this->names($codeCall->argument(0), $column) && $list instanceof CodeList
            ? $this->texts($list)
            : [];
    }

    /**
     * @param CodeNode|null $codeNode A term.
     * @param string        $column   A column.
     *
     * @return bool Whether the term is that column.
     */
    private function names(?CodeNode $codeNode, string $column): bool
    {
        $name = $codeNode instanceof CodeCall && $codeNode->method === 'column'
            ? $codeNode->valueArgument(0)
            : null;

        return $name instanceof CodeValue && $this->phpLiteral->text($name->php) === $column;
    }

    /**
     * @param CodeList $codeList A list of terms.
     *
     * @return list<string> The texts, when every term is a text literal; otherwise none.
     */
    private function texts(CodeList $codeList): array
    {
        $values = [];

        foreach ($codeList->items as $item) {
            $text = $this->text($item);

            if ($text === null) {
                return [];
            }

            $values[] = $text;
        }

        return $values;
    }

    /**
     * @param CodeNode $codeNode A term.
     *
     * @return string|null The text, when the term is a text literal; otherwise null.
     */
    private function text(CodeNode $codeNode): ?string
    {
        $text = $codeNode instanceof CodeCall && $codeNode->method === 'text'
            ? $codeNode->valueArgument(0)
            : null;

        return $text instanceof CodeValue
            ? $this->phpLiteral->text($text->php)
            : null;
    }
}
