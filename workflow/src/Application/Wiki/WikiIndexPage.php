<?php

declare(strict_types=1);

namespace AIC\Workflow\Application\Wiki;

use AIC\Workflow\Domain\Console\SurfaceModule;
use AIC\Workflow\Domain\Console\SurfaceView;

use function array_count_values;
use function array_map;
use function implode;
use function ksort;
use function rtrim;
use function sprintf;

/**
 * The wiki's index, `docs/wiki/README.md` (#108): every module in build
 * order with its namespace, requires, dependents, routes by kind and class
 * count; the requires graph as a mermaid block (gate:19 skips fenced
 * blocks); the routes by kind; the commands, jobs and schedules; and a link
 * to AIC's architecture pages.
 */
final readonly class WikiIndexPage
{
    /**
     * The modules table's columns.
     */
    private const array MODULES = ['Module', 'Namespace', 'Requires', 'Required by', 'Routes', 'Classes'];

    /**
     * One requires edge in the mermaid graph.
     */
    private const string EDGE = '    %s --> %s';

    /**
     * The commands and jobs tables' columns.
     */
    private const array NAMED = ['Name', 'Module', 'Class'];

    /**
     * The schedules table's columns.
     */
    private const array SCHEDULES = ['Name', 'Cadence', 'Job', 'Module'];

    /**
     * @param WikiMarkdown $wikiMarkdown Tables, spans and lists.
     * @param WikiLinks    $wikiLinks    The module pages and the architecture pages.
     */
    public function __construct(
        private WikiMarkdown $wikiMarkdown,
        private WikiLinks $wikiLinks,
    ) {
    }

    /**
     * @param SurfaceView        $surfaceView The surface.
     * @param array<string, int> $classes     Each module's class count.
     *
     * @return string The index.
     */
    public function render(SurfaceView $surfaceView, array $classes): string
    {
        $markdown = $this->wikiMarkdown;
        $kinds = $markdown->table(['Kind', 'Routes'], self::kinds($surfaceView), 'bin/aic kind:list');
        $modules = $markdown->table(self::MODULES, $this->modules($surfaceView, $classes), 'bin/aic module:list');
        $commands = $markdown->table(self::NAMED, $this->named($surfaceView->commands), 'bin/aic command:list');
        $schedules = $markdown->table(self::SCHEDULES, $this->schedules($surfaceView), 'bin/aic schedule:list');
        $routes = $markdown->table(['Method', 'Path', 'Kind', 'Module', 'Handler'], $this->routes($surfaceView), 'bin/aic route:list');
        $lines = [
            '# Code wiki',
            '',
            'Generated by `composer run build` from the module manifests, `build/surface.json` and the code index; an edit here fails '
                . 'gate:24. How AIC works: ' . $markdown->link('the architecture pages', $this->wikiLinks->architecture()) . '.',
            '',
            ...$markdown->section('## Modules', $modules),
            ...$markdown->section('## Requires', ['```mermaid', 'graph LR', ...$this->graph($surfaceView), '```']),
            ...$markdown->section('## Routes by kind', [...$kinds, '', ...$routes]),
            ...$markdown->section('## Commands', $commands),
            ...$markdown->section('## Jobs', $markdown->table(self::NAMED, $this->named($surfaceView->jobs), 'bin/aic job:list')),
            ...$markdown->section('## Schedules', $schedules),
        ];

        return rtrim(implode("\n", $lines)) . "\n";
    }

    /**
     * @param SurfaceView        $surfaceView The surface.
     * @param array<string, int> $classes     Each module's class count.
     *
     * @return list<list<string>> One row per module, in build order.
     */
    private function modules(SurfaceView $surfaceView, array $classes): array
    {
        return array_map(fn (SurfaceModule $surfaceModule): array => [
            $this->wikiMarkdown->link($surfaceModule->name, $this->wikiLinks->module($surfaceModule->name, true)),
            $this->wikiMarkdown->code($surfaceModule->namespace),
            $this->wikiMarkdown->inline($surfaceModule->requires),
            $this->wikiMarkdown->inline($surfaceView->dependents($surfaceModule->name)),
            self::routeKinds($surfaceView, $surfaceModule->name),
            (string) ($classes[$surfaceModule->name] ?? 0),
        ], $surfaceView->modules);
    }

    /**
     * @param SurfaceView $surfaceView The surface.
     *
     * @return list<string> One `a --> b` line per requires, in build order.
     */
    private function graph(SurfaceView $surfaceView): array
    {
        $edges = [];

        foreach ($surfaceView->modules as $surfaceModule) {
            $name = $surfaceModule->name;
            $edges = $surfaceModule->requires === []
                ? [...$edges, '    ' . $name]
                : [...$edges, ...array_map(
                    static fn (string $required): string => sprintf(self::EDGE, $name, $required),
                    $surfaceModule->requires,
                )];
        }

        return $edges;
    }

    /**
     * @param SurfaceView $surfaceView The surface.
     *
     * @return list<list<string>> Each route's row, in surface order.
     */
    private function routes(SurfaceView $surfaceView): array
    {
        return array_map(fn (array $route): array => [
            $route['method'],
            $this->wikiMarkdown->code($route['path']),
            $route['kind'],
            $this->wikiMarkdown->link($route['module'], $this->wikiLinks->module($route['module'], true)),
            $this->wikiMarkdown->code($route['handler']),
        ], $surfaceView->routes);
    }

    /**
     * @param list<array{class: string, kind: string, module: string, name: string}> $entries Commands or jobs.
     *
     * @return list<list<string>> Each one's name, module and class.
     */
    private function named(array $entries): array
    {
        return array_map(fn (array $entry): array => [
            $this->wikiMarkdown->code($entry['name']),
            $entry['module'],
            $this->wikiMarkdown->code($entry['class']),
        ], $entries);
    }

    /**
     * @param SurfaceView $surfaceView The surface.
     *
     * @return list<list<string>> Each schedule's row.
     */
    private function schedules(SurfaceView $surfaceView): array
    {
        return array_map(
            fn (array $schedule): array => [...$this->wikiMarkdown->schedule($schedule), $schedule['module']],
            $surfaceView->schedules,
        );
    }

    /**
     * @param SurfaceView $surfaceView The surface.
     *
     * @return list<list<string>> Each kind with its route count, kinds sorted.
     */
    private static function kinds(SurfaceView $surfaceView): array
    {
        $counts = array_count_values(array_map(static fn (array $route): string => $route['kind'], $surfaceView->routes));
        ksort($counts);
        $rows = [];

        foreach ($counts as $kind => $count) {
            $rows[] = [$kind, (string) $count];
        }

        return $rows;
    }

    /**
     * @param SurfaceView $surfaceView The surface.
     * @param string      $module      A module.
     *
     * @return string Its routes counted by kind, kinds sorted; `none` when it has none.
     */
    private static function routeKinds(SurfaceView $surfaceView, string $module): string
    {
        $kinds = [];

        foreach ($surfaceView->routes as $route) {
            $kinds = $route['module'] === $module
                ? [...$kinds, $route['kind']]
                : $kinds;
        }

        $counts = array_count_values($kinds);
        ksort($counts);
        $parts = [];

        foreach ($counts as $kind => $count) {
            $parts[] = $kind . ' ' . $count;
        }

        return $parts === []
            ? 'none'
            : implode(', ', $parts);
    }
}
