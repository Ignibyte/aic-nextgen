<?php

declare(strict_types=1);

namespace AIC\Workflow\Application\Wiki;

use AIC\Workflow\Domain\CodeCrossing;
use AIC\Workflow\Domain\CodeSymbol;
use AIC\Workflow\Domain\Console\SurfaceModule;
use AIC\Workflow\Domain\Console\SurfaceView;
use AIC\Workflow\Exception\WorkflowRefusal;

use function array_map;
use function implode;
use function in_array;
use function rtrim;
use function sort;

/**
 * One module's wiki page (#108): generated whole from the surface and the
 * code index, the same facts giving the same bytes (no date, no commit, no
 * absolute path). It links the module's hand-written notes, `README.md`
 * beside its manifest, and copies nothing from them.
 */
final readonly class WikiModulePage
{
    /**
     * @param WikiMarkdown $wikiMarkdown Tables, spans and lists.
     * @param WikiLinks    $wikiLinks    Files, module pages, kinds and systems.
     * @param WikiManifest $wikiManifest The manifest sections.
     * @param WikiClasses  $wikiClasses  The classes section.
     * @param WikiUsage    $wikiUsage    The uses and used-by sections.
     */
    public function __construct(
        private WikiMarkdown $wikiMarkdown,
        private WikiLinks $wikiLinks,
        private WikiManifest $wikiManifest,
        private WikiClasses $wikiClasses,
        private WikiUsage $wikiUsage,
    ) {
    }

    /**
     * @param SurfaceModule      $surfaceModule The module.
     * @param SurfaceView        $surfaceView   The surface.
     * @param list<CodeSymbol>   $symbols       The symbols in its files.
     * @param list<string>       $files         Its files.
     * @param list<CodeCrossing> $crossings     The references across its edge.
     *
     * @throws WorkflowRefusal When a framework system it uses has no section in `systems.md`.
     *
     * @return string The page.
     */
    public function render(
        SurfaceModule $surfaceModule,
        SurfaceView $surfaceView,
        array $symbols,
        array $files,
        array $crossings,
    ): string {
        $name = $surfaceModule->name;
        $lines = [
            '# Module ' . $this->wikiMarkdown->code($name),
            '',
            'Generated by `composer run build` from the manifest and the code; an edit here fails gate:24. ' . $this->notes($name, $files),
            '',
            ...$this->head($surfaceModule, $surfaceView),
            '',
            ...$this->wikiManifest->lines($surfaceModule, $surfaceView),
            ...$this->wikiClasses->lines($name, $symbols, $files, $surfaceModule->declarations),
            ...$this->wikiUsage->lines($name, $crossings),
        ];

        return rtrim(implode("\n", $lines)) . "\n";
    }

    /**
     * @param SurfaceModule $surfaceModule The module.
     * @param SurfaceView   $surfaceView   The surface.
     *
     * @return list<string> The namespace, the manifest, requires, required by and exports.
     */
    private function head(SurfaceModule $surfaceModule, SurfaceView $surfaceView): array
    {
        $name = $surfaceModule->name;
        $manifest = 'modules/' . $name . '/' . $name . '.module.php';

        return [
            '- Namespace: ' . $this->wikiMarkdown->code($surfaceModule->namespace),
            '- Manifest: ' . $this->wikiMarkdown->link($manifest, $this->wikiLinks->file($manifest, false)),
            '- Requires: ' . $this->wikiMarkdown->inline($this->modules($surfaceModule->requires)),
            '- Required by: ' . $this->wikiMarkdown->inline($this->modules($surfaceView->dependents($name))),
            '- Exports: ' . $this->wikiMarkdown->inline(array_map($this->wikiMarkdown->code(...), $surfaceModule->exports)),
        ];
    }

    /**
     * @param list<string> $modules Module names.
     *
     * @return list<string> Each linked to its page, sorted.
     */
    private function modules(array $modules): array
    {
        sort($modules);

        return array_map(
            fn (string $module): string => $this->wikiMarkdown->link($module, $this->wikiLinks->module($module, false)),
            $modules,
        );
    }

    /**
     * @param string       $module The module.
     * @param list<string> $files  Its files.
     *
     * @return string Where its notes are: a link when `README.md` is there, the path to create otherwise.
     */
    private function notes(string $module, array $files): string
    {
        $readme = 'modules/' . $module . '/README.md';

        return in_array($readme, $files, true)
            ? 'Notes about this module: ' . $this->wikiMarkdown->link($readme, $this->wikiLinks->file($readme, false)) . '.'
            : 'Notes about this module go in `' . $readme . '`.';
    }
}
